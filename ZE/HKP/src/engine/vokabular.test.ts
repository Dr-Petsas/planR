import { describe, expect, it } from 'vitest'
import { hkpEntwurf } from '../clara'
import { auftragVerstehen } from './auftrag'
import { prothetikIn } from './vokabular'

const ok = (r: ReturnType<typeof hkpEntwurf>): Extract<typeof r, { status: 'ok' }> => {
  if (r.status !== 'ok') throw new Error(r.frage)
  return r
}
const nr = (r: ReturnType<typeof ok>) => r.ergebnis.positionen.map((p) => `${p.ebene} ${p.nr}`)
const hat = (r: ReturnType<typeof ok>, code: string) => nr(r).includes(code)
const UK = Object.fromEntries(['48', '47', '46', '45', '44', '43', '42', '41', '31', '32', '33', '34', '35', '36', '37', '38'].map((z) => [z, 'f']))

describe('Vokabular Suprakonstruktion und Krone', () => {
  it('erkennt die gesprochenen Formen', () => {
    expect(prothetikIn('verschraubte Implantatkronen').versorgung).toBe('implantatkronen')
    expect(prothetikIn('verschraubte Implantatkronen').retention).toBe('verschraubt')
    expect(prothetikIn('zementierte Implantatkrone, individuelles Keramikabutment')).toMatchObject({ retention: 'zementiert', abutment: 'keramik' })
    expect(prothetikIn('Suprakonstruktion auf 36').versorgung).toBe('implantatkronen')
    expect(prothetikIn('Implantatsteg auf 34 und 44').versorgung).toBe('steg')
    expect(prothetikIn('Druckknopfprothese mit Patrize und Matrize').anker).toBe('locator')
    expect(prothetikIn('Kugelkopfanker auf Implantaten').anker).toBe('kugel')
    expect(prothetikIn('Locator auf 33 und 43').anker).toBe('locator')
    expect(prothetikIn('All-on-4 im Unterkiefer')).toMatchObject({ versorgung: 'allon', allon: 4 })
    expect(prothetikIn('all on sechs ZE').allon).toBe(6)
    expect(prothetikIn('Orlon-6-Prothese').allon).toBe(6)
    expect(prothetikIn('Allon 4').allon).toBe(4)
    expect(prothetikIn('Implantatprothese All-on-6 Oberkiefer').versorgung).toBe('allon')
    expect(prothetikIn('vollanatomische Zirkonkrone')).toMatchObject({ versorgung: 'kronen', form: 'vollanatomisch' })
    expect(prothetikIn('NEM Krone').versorgung).toBe('kronen')
    expect(prothetikIn('Gerüst mit Verblendung').versorgung).toBe('kronen')
    expect(prothetikIn('Inlay 16 mod')).toMatchObject({ versorgung: 'inlay', kronenart: 'inlay', flaechen: 3 })
    expect(prothetikIn('Onlay 15').kronenart).toBe('onlay')
    expect(prothetikIn('Tabletop 26').kronenart).toBe('tabletop')
    expect(prothetikIn('Teilkrone 24').kronenart).toBe('teilkrone')
    expect(prothetikIn('Galvanokrone 11').kronenart).toBe('galvano')
    expect(prothetikIn('Galvanoteleskop 13').versorgung).toBe('teleskopprothese')
    expect(prothetikIn('Primärteleskop aus Zirkon').versorgung).toBe('teleskopprothese')
    expect(prothetikIn('Zirkonteleskop 13 und 23').sekundaer).toBeFalsy()
    expect(auftragVerstehen('NEM mit Keramikverblendung').verblendung).toBeUndefined()
    expect(auftragVerstehen('NEM Krone').werkstoff).toBe('nem')
    expect(auftragVerstehen('Gerüst mit Verblendung auf 16').verblendung).toBe('teil')
    expect(auftragVerstehen('Presskeramikkrone 21').werkstoff).toBe('presskeramik')
  })

  it('verschraubte Implantatkronen: individuelles Abutment, keine GOZ 5080', () => {
    const r = ok(hkpEntwurf('verschraubte Implantatkronen auf 14 und 15', { 14: 'f', 15: 'f' }))
    expect(r.plan.zaehne['14'].TP).toBe('SK')
    expect(r.plan.implantat.abutment).toBe('individuell')
    expect(hat(r, 'GOZ 2200')).toBe(true)
    expect(hat(r, 'GOZ 9050')).toBe(true)
    expect(hat(r, 'BEB 2033')).toBe(true)
    expect(hat(r, 'GOZ 5080')).toBe(false)
    expect(hat(r, 'BEB 4421')).toBe(false)
    expect(r.plan.einstellungen.haltung).toContain('verschraubte')
  })

  it('zementierte Krone auf Keramikabutment', () => {
    const r = ok(hkpEntwurf('zementierte Implantatkrone 36, individuelles Keramikabutment', { 36: 'f' }))
    expect(r.plan.implantat.abutment).toBe('keramik')
    expect(hat(r, 'BEB 6906')).toBe(true)
    expect(hat(r, 'BEB 2033')).toBe(false)
    expect(hat(r, 'GOZ 5080')).toBe(false)
  })

  it('Druckknopfprothese: 5030 und 5080, Matrize und Patrize ein Element', () => {
    const r = ok(hkpEntwurf('Druckknopfprothese im Unterkiefer auf 33 und 43', UK))
    expect(r.plan.zaehne['33'].TP).toBe('SO')
    expect(r.plan.zaehne['43'].TP).toBe('SO')
    expect(r.plan.zaehne['36'].TP).toBe('E')
    expect(hat(r, 'GOZ 5030')).toBe(true)
    expect(hat(r, 'GOZ 5080')).toBe(true)
    expect(hat(r, 'BEB 3027')).toBe(true)
    expect(hat(r, 'GOZ 5230')).toBe(true)
    expect(r.zusammenfassung.ankerGesagt).toBe('Druckknopfanker')
  })

  it('Implantatsteg spannt nur zwischen den Implantaten', () => {
    const r = ok(hkpEntwurf('Implantatsteg im Unterkiefer auf 34 und 44', UK))
    expect(r.plan.zaehne['34'].TP).toBe('SO')
    expect(r.plan.zaehne['44'].TP).toBe('SO')
    expect(r.plan.zaehne['41'].TP).toBe('SEO')
    expect(r.plan.zaehne['36'].TP).toBe('E')
    expect(hat(r, 'GOZ 5070')).toBe(true)
    expect(hat(r, 'GOZ 5030')).toBe(true)
    expect(hat(r, 'BEB 2035')).toBe(true)
    expect(r.zusammenfassung.ankerGesagt).toBe('Implantatsteg')
  })

  it('All-on-4 nimmt die üblichen Sitze und bleibt eine Brücke', () => {
    const r = ok(hkpEntwurf('All-on-4 im Unterkiefer', {}))
    expect(r.plan.zaehne['45'].TP).toBe('SK')
    expect(r.plan.zaehne['42'].TP).toBe('SK')
    expect(r.plan.zaehne['32'].TP).toBe('SK')
    expect(r.plan.zaehne['35'].TP).toBe('SK')
    expect(r.plan.zaehne['44'].TP).toBe('SB')
    expect(r.plan.zaehne['46'].TP).toBe(')(')
    expect(hat(r, 'GOZ 5000')).toBe(true)
    expect(hat(r, 'GOZ 5070')).toBe(true)
    expect(hat(r, 'GOZ 5230')).toBe(false)
    expect(hat(r, 'GOZ 5080')).toBe(false)
    expect(r.hinweise.some((h) => h.includes('45, 42, 32, 35'))).toBe(true)
    expect(r.zusammenfassung.ankerGesagt).toBe('All-on-4')
  })

  it('All-on-6 oben und unten sitzt auf bestehenden Implantaten', () => {
    const okZaehne = Object.fromEntries(['18', '17', '16', '15', '14', '13', '12', '11', '21', '22', '23', '24', '25', '26', '27', '28'].map((z) => [z, 'f']))
    for (const z of ['16', '14', '24', '26']) okZaehne[z] = 'sk'
    const ukZaehne = Object.fromEntries(['48', '47', '46', '45', '44', '43', '42', '41', '31', '32', '33', '34', '35', '36', '37', '38'].map((z) => [z, 'f']))
    for (const z of ['46', '44', '42', '32', '34', '36']) ukZaehne[z] = 'i'
    const a = auftragVerstehen('Plan direkt die All-on-6-Prothesen oben und unten')
    expect(a.teile?.map((x) => [x.kiefer, x.versorgung, x.allon])).toEqual([['OK', 'allon', 6], ['UK', 'allon', 6]])
    const r = ok(hkpEntwurf('Plan direkt die All-on-6-Prothesen oben und unten', { ...okZaehne, ...ukZaehne }))
    expect(r.plan.zaehne['16'].TP).toBe('SK')
    expect(r.plan.zaehne['12'].TP).toBe('SK')
    expect(r.plan.zaehne['13'].TP).toBe('SB')
    expect(r.plan.zaehne['46'].TP).toBe('SK')
    expect(r.plan.zaehne['36'].TP).toBe('SK')
    expect(r.zusammenfassung.ankerGesagt).toBe('All-on-6')
    expect(r.hinweise.some((h) => h.includes('Implantate an 16, 14, 24 und 26 bleiben'))).toBe(true)
    const zahn = hkpEntwurf('All-on-6 im Oberkiefer', { ...okZaehne, '13': '' })
    expect(zahn.status).toBe('rueckfrage')
    if (zahn.status === 'rueckfrage') {
      expect(zahn.zaehne).toEqual(['13'])
      expect(zahn.frage).toMatch(/All-on-6/)
      expect(zahn.frage).toMatch(/Zahn 13/)
    }
    const verhoert = ok(hkpEntwurf('Orlon-6 im Oberkiefer', okZaehne))
    expect(verhoert.plan.zaehne['16'].TP).toBe('SK')
    expect(verhoert.zusammenfassung.ankerGesagt).toBe('All-on-6')
  })

  it('vollanatomische Zirkonkrone ist nicht die verblendete Keramikkrone', () => {
    const voll = ok(hkpEntwurf('vollanatomische Zirkonkrone 16', { 16: 'ww' }))
    const front = ok(hkpEntwurf('vollanatomische Zirkonkrone 11', { 11: 'ww' }))
    const verblendet = ok(hkpEntwurf('Zirkonkrone 16', { 16: 'ww' }))
    expect(voll.plan.zaehne['16'].TP).toBe('ZA')
    expect(hat(voll, 'BEB 2251')).toBe(true)
    expect(hat(voll, 'BEB 2612')).toBe(false)
    expect(hat(voll, 'BEB 2281')).toBe(false)
    expect(hat(front, 'BEB 2252')).toBe(true)
    expect(verblendet.plan.zaehne['16'].TP).toBe('KM')
    expect(hat(verblendet, 'BEB 2281')).toBe(true)
    expect(hat(verblendet, 'BEB 2612')).toBe(true)
  })

  it('Gerüst, Inlay, Teilkrone, Tabletop, Galvano und Zirkonteleskop', () => {
    expect(ok(hkpEntwurf('Gerüst mit Verblendung auf 16', { 16: 'ww' })).plan.zaehne['16'].TP).toBe('KV')
    const inlay = ok(hkpEntwurf('Inlay 16', { 16: '' }))
    expect(inlay.plan.zaehne['16'].TP).toBe('I2')
    expect(hat(inlay, 'GOZ 2160')).toBe(true)
    expect(hat(inlay, 'BEB 2302')).toBe(true)
    expect(hat(inlay, 'GOZ 2210')).toBe(false)
    const keramik = ok(hkpEntwurf('Keramikinlay 16 mod', { 16: '' }))
    expect(keramik.plan.zaehne['16'].TP).toBe('C3')
    expect(hat(keramik, 'GOZ 2170')).toBe(true)
    expect(hat(keramik, 'BEB 2553')).toBe(true)
    const teil = ok(hkpEntwurf('Teilkrone 16', { 16: '' }))
    expect(teil.plan.zaehne['16'].TP).toBe('PK')
    expect(hat(teil, 'GOZ 2220')).toBe(true)
    const top = ok(hkpEntwurf('Tabletop 26', { 26: '' }))
    expect(top.plan.zaehne['26'].TP).toBe('PK')
    expect(top.hinweise.some((h) => h.includes('Tabletop'))).toBe(true)
    const galvano = ok(hkpEntwurf('Galvanokrone 11', { 11: 'ww' }))
    expect(galvano.plan.zaehne['11'].TP).toBe('K')
    expect(galvano.plan.werkstoffe?.['11']).toBe('hochgold')
    expect(hat(galvano, 'BEB 2101')).toBe(true)
    expect(hat(galvano, 'BEB 2611')).toBe(false)
    expect(galvano.hinweise.some((h) => h.includes('keine eigene Galvanoposition'))).toBe(true)
    const tel = ok(hkpEntwurf('Zirkonteleskop auf 13 und 23', { 13: '', 23: '' }))
    expect(tel.plan.zaehne['13'].TP).toBe('TZ')
    expect(hat(tel, 'GOZ 5040')).toBe(true)
    expect(hat(tel, 'BEB 3001')).toBe(true)
    expect(hat(tel, 'BEB 6905')).toBe(true)
    expect(hat(tel, 'BEB 2281')).toBe(false)
    const gtel = ok(hkpEntwurf('Galvanoteleskop auf 13 und 23', { 13: '', 23: '' }))
    expect(gtel.plan.zaehne['13'].TP).toBe('T')
    expect(hat(gtel, 'BEB 6905')).toBe(false)
    expect(gtel.plan.werkstoffe?.['13']).toBe('hochgold')
    expect(hkpEntwurf('Suprakonstruktion', { 36: 'f' }).status).toBe('rueckfrage')
  })
})
